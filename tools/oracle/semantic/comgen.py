#!/usr/bin/env python3
"""comgen.py - a DCL semantic-oracle probe from a DCL spec (rd vms-8d1).

A DCL family (tools/oracle/semantic/specs-dcl/<family>.py) lists SETUP lines and
CASES of (CASE-ID, DCL expression). This writes SP_<FAMILY>.COM, which the real
OpenVMS node and OVMX both run with @: for each case it assigns the expression
to a symbol and prints

    <CASE-ID> st=<$STATUS hex> t=<F$TYPE of the result> v="<the result>"

between the "=== SEMPROBE <family> BEGIN/END ===" markers semantic_diff.py
reads -- the same transcript shape as a MACRO/C probe. An expression DCL
refuses leaves the symbol empty ("") and its error status in st (a SET NOON
before each case gives $STATUS a success value first, so st is this case's);
the message DCL prints for it is not a case line and is not compared.

A family that sets KIND = "IF" lists IF CONDITIONS instead of expressions
(rd vms-c17a): each case runs "IF <condition> THEN SP_V = "T"" with SP_V
preset to "F" and prints

    <CASE-ID> v=<T or F>

so the transcript is what the IF decided -- the operator precedence and operand
evaluation of DCL's IF, not the assignment evaluator.

A family that sets KIND = "CALL" lists command SEQUENCES instead (the ON
family): each case is the body of its own SUBROUTINE, entered with CALL from a
SET NOON driver so it runs at a fresh procedure level. The body records what it
reached in the global symbol SP_T, and the case prints

    <CASE-ID> t=<SP_T> st=<the CALL's $STATUS, hex>

SUBS names further subroutines the bodies call (one DCL line per list item).
TEARDOWN lists DCL lines run after the last case (any KIND), e.g. to restore a
default directory SETUP changed.

  comgen.py <specs-dcl/family.py>      the .COM on stdout
"""
import os
import sys


def load(spec):
    g = {}
    exec(compile(open(spec).read(), spec, "exec"), g)
    return (os.path.splitext(os.path.basename(spec))[0], g.get("SETUP", []), g["CASES"],
            g.get("KIND", "EXPR"), g.get("SUBS", {}), g.get("TEARDOWN", []))


def gen(spec):
    fam, setup, cases, kind, subs, teardown = load(spec)
    assert kind in ("EXPR", "IF", "CALL"), "unknown KIND %r" % kind
    seen = set()
    out = ["$! SP_%s.COM -- generated by tools/oracle/semantic/comgen.py from" % fam.upper(),
           "$! tools/oracle/semantic/specs-dcl/%s.py (rd vms-8d1). DO NOT EDIT." % fam,
           "$ SET NOON",
           '$ WRITE SYS$OUTPUT "=== SEMPROBE %s BEGIN ==="' % fam]
    for ln in setup:
        out.append("$ " + ln)
    for cid, expr in cases:
        assert cid not in seen, "duplicate case %s" % cid
        seen.add(cid)
        if kind == "CALL":
            out.append('$ SP_T == ""')
            out.append("$ CALL SP_C%d" % len(seen))
            out.append("$ SP_ST = $STATUS")
            out.append('$ WRITE SYS$OUTPUT "%s t=", SP_T, " st=", F$FAO("!XL", F$INTEGER(SP_ST))'
                       % cid)
            continue
        if kind == "IF":
            out.append('$ SP_V = "F"')
            out.append("$ IF %s THEN SP_V = \"T\"" % expr)
            out.append('$ WRITE SYS$OUTPUT "%s v=", SP_V' % cid)
            continue
        out.append('$ SP_V = ""')
        out.append("$ SET NOON")          # a command: $STATUS is its success
        out.append("$ SP_V = %s" % expr)
        out.append("$ SP_ST = $STATUS")
        out.append('$ WRITE SYS$OUTPUT "%s st=", F$FAO("!XL", F$INTEGER(SP_ST)), " t=", F$TYPE(SP_V), " v=""", SP_V, """"'
                   % cid)
    for ln in teardown:
        out.append("$ " + ln)
    out.append('$ WRITE SYS$OUTPUT "=== SEMPROBE %s END ==="' % fam)
    out.append("$ EXIT")
    if kind == "CALL":
        bodies = [("SP_C%d" % (i + 1), body) for i, (_, body) in enumerate(cases)]
        for name, body in bodies + sorted(subs.items()):
            out.append("$ %s: SUBROUTINE" % name)
            out += ["$ " + ln for ln in body]
            out.append("$ ENDSUBROUTINE")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    sys.stdout.write(gen(sys.argv[1]))
