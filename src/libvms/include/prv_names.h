/* Expands to one `{ "NAME", mask, "desc" },` per VMS_PRIV_NAME_LIST entry.
 * Used by dcl_cmd_show.c to build vms_priv_names[]. */
#define VMS_PRIV_ROW_ENTRY(name, mask, desc) { #name, mask, desc },

/* Expands to `| (mask)` per entry; OR'd against 0 below to produce a single
 * compile-time constant covering every bit ANY row in the table sets. Used
 * by prv_agreement.c to check VMS_PRV_M_ENFORCED against the table's real
 * content instead of a hand-copied subset. */
#define VMS_PRIV_MASK_TERM(name, mask, desc) | (mask)
#define VMS_PRIV_NAMES_TABLE_MASK (0 VMS_PRIV_NAME_LIST(VMS_PRIV_MASK_TERM))

