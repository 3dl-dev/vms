/* A condition's message identity (facility + number), severity ignored. */
#define COND_ID(c) ((uint32_t)(c) & 0x0FFFFFF8u)
#define SEV_SEVERE 4u

/* ------------------------------------------------- the signal table ------ */

/* Table 4-5: the OpenVMS exception raise() signals for each signal. 0 = no
 * pinned condition: the C RTL delivers the signal itself. */
static uint32_t sig_cond(int sig)
{
    switch (sig) {
    case SIGABRT: return SS_OPCCUS;          /* SIGIOT is SIGABRT here */
    case SIGALRM: return SS_ASTFLT;
    case SIGBUS:  return SS_ACCVIO;
    case SIGSEGV: return SS_ACCVIO;
#ifdef SIGEMT
    case SIGEMT:  return SS_COMPAT;
#endif
    case SIGFPE:  return SS_HPARITH;
    case SIGHUP:  return SS_HANGUP;
    case SIGILL:  return SS_OPCDEC;
    case SIGINT:  return SS_CONTROLC;
    case SIGKILL: return SS_ABORT;
    case SIGQUIT: return SS_CONTROLY;
    case SIGPIPE: return SS_NOMBX;
    case SIGSYS:  return SS_BADPARAM;
    case SIGTRAP: return SS_BREAK;
    default:      return 0;
    }
}

/* The reverse of Table 4-5, for a condition the C RTL did not raise itself (a
 * fault LIBVMS's bridge signalled, or a program's own LIB$SIGNAL). sa is the
 * signal array; an ACCVIO's reason mask bit 0 is a length violation (SIGSEGV),
 * otherwise an access violation (SIGBUS). */
static int cond_sig(const uint32_t *sa)
{
    switch (COND_ID(sa[1])) {
    case COND_ID(SS_ACCVIO):
        return (sa[0] >= 2 && (sa[2] & 1u)) ? SIGSEGV : SIGBUS;
    case COND_ID(SS_CMODUSER): return SIGBUS;
    case COND_ID(SS_CMODSUPR): return SIGSEGV;
    case COND_ID(SS_OPCCUS):   return SIGABRT;
    case COND_ID(SS_ASTFLT):   return SIGALRM;
#ifdef SIGEMT
    case COND_ID(SS_COMPAT):   return SIGEMT;
#endif
    case COND_ID(SS_HPARITH): case COND_ID(SS_INTDIV): case COND_ID(SS_DECOVF):
    case COND_ID(SS_DECDIV):  case COND_ID(SS_DECINV): case COND_ID(SS_SUBRNG):
        return SIGFPE;
    case COND_ID(SS_HANGUP):   return SIGHUP;
    case COND_ID(SS_OPCDEC): case COND_ID(SS_ROPRAND): return SIGILL;
    case COND_ID(SS_CONTROLC): return SIGINT;
    case COND_ID(SS_CONTROLY): return SIGQUIT;
    case COND_ID(SS_NOMBX):    return SIGPIPE;
    case COND_ID(SS_BADPARAM): return SIGSYS;
    case COND_ID(SS_BREAK): case COND_ID(SS_TBIT): return SIGTRAP;
    default: return 0;
    }
}

/* ------------------------------------------------------ RTL state ------- */

#define SIG_MAX 31                     /* DEC C signals: 1..31 (Table 4-5) */
#define BIT(s) (1ull << ((s) - 1))
#define UNBLOCKABLE (BIT(SIGKILL) | BIT(SIGSTOP))

/* musl's rt_sigaction argument (src/internal/ksigaction.h, the generic layout
 * both the x86_64 and the alpha-dec-vms port use), read as musl wrote it. */
struct crtl_ksa {
    void (*handler)(int);
    unsigned long flags;
#ifdef SA_RESTORER
    void (*restorer)(void);
#endif
    unsigned mask[2];
#ifndef SA_RESTORER
    void *unused;
#endif
};

static struct { void (*handler)(int); unsigned long flags; uint64_t mask; } sig_act[SIG_MAX + 1];
static uint64_t sig_mask;              /* the C RTL's signal mask */
static volatile uint64_t sig_pending;  /* raised while blocked (or while busy) */
static volatile unsigned sig_delivered;/* actions run: pause()/sigsuspend() wait on it */
static int sig_on;                     /* set by ovmx_crtl_signal_install */
volatile int ovmx_crtl_sig_busy;       /* the file layer is inside RMS */

static int raising;                    /* the signal raise() is signalling */
static int raise_seen;                 /* ... reached the C RTL's handler */

static int sig_ignored_by_default(int sig) { return sig == SIGCHLD; }

/* The image ends as a signal's default action does: $EXIT with its condition
 * at severity F (SS$_ABORT where Table 4-5 has none). */
static void sig_terminate(int sig)
{
    uint32_t c = sig_cond(sig);
    if (!c)
        c = SS_ABORT;
    (void)sys$exit((c & ~7u) | SEV_SEVERE);
}

/* Run the program's action for sig (caught: a function). */
static void sig_run(int sig, const uint32_t *sa)
{
    void (*h)(int) = sig_act[sig].handler;
    unsigned long fl = sig_act[sig].flags;
    uint64_t saved = sig_mask;

    sig_mask |= sig_act[sig].mask | ((fl & SA_NODEFER) ? 0 : BIT(sig));
    sig_mask &= ~UNBLOCKABLE;
    if (fl & SA_RESETHAND) {
        sig_act[sig].handler = SIG_DFL;
        sig_act[sig].flags &= ~(unsigned long)SA_SIGINFO;
    }
    if (fl & SA_SIGINFO) {
        siginfo_t si;
        static ucontext_t uc;          /* no substrate machine context: zeroed */
        memset(&si, 0, sizeof si);
        si.si_signo = sig;
        si.si_code = SI_USER;
        if (sa && COND_ID(sa[1]) == COND_ID(SS_ACCVIO) && sa[0] >= 3)
            si.si_addr = (void *)(uintptr_t)sa[3];
        ((void (*)(int, siginfo_t *, void *))(void *)h)(sig, &si, &uc);
    } else {
        h(sig);
    }
    sig_mask = saved;
    sig_delivered++;
}

/* The secondary exception vector: a condition with a caught signal runs its
 * action and is continued; every other condition is resignalled. */
static unsigned int sig_condition(void *sigarr, void *mecharr)
{
    const uint32_t *sa = (const uint32_t *)sigarr;
    int sig;
    (void)mecharr;

    if (raising && COND_ID(sa[1]) == COND_ID(sig_cond(raising)))
        sig = raising, raise_seen = 1;
    else
        sig = cond_sig(sa);
    if (!sig || sig > SIG_MAX)
        return SS_RESIGNAL;
    void (*h)(int) = sig_act[sig].handler;
    if (h == SIG_IGN)
        return SS_CONTINUE;
    if (h == SIG_DFL || (sig_mask & BIT(sig)))
        return SS_RESIGNAL;            /* the VMS default: last chance, exit */
    sig_run(sig, sa);
    return SS_CONTINUE;
}

/* Deliver sig now: signal its condition, or run its action directly. */
static void sig_deliver(int sig)
{
    void (*h)(int) = sig_act[sig].handler;
    uint32_t c = sig_cond(sig);

    if (h == SIG_IGN || (h == SIG_DFL && sig_ignored_by_default(sig)))
        return;
    if (sig == SIGKILL) {
        sig_terminate(sig);
        return;
    }
    if (sig == SIGSTOP || (h == SIG_DFL && (sig == SIGTSTP || sig == SIGTTIN || sig == SIGTTOU))) {
        (void)sys$suspnd(0, 0, 0);     /* the process itself: $SUSPND */
        return;
    }
    if (c) {
        int prev = raising, prev_seen = raise_seen;
        raising = sig;
        raise_seen = 0;
        if (c == SS_ACCVIO)            /* reason mask: SIGSEGV a length violation */
            (void)lib$signal(c, 4u, sig == SIGSEGV ? 1u : 0u, 0u, 0u, 0u);
        else
            (void)lib$signal(c, 0u);
        int seen = raise_seen;
        raising = prev;
        raise_seen = prev_seen;
        /* No frame handler claimed it and the action is the default: a
         * condition the VMS default let continue (a success-severity
         * SS$_CONTROLC) still ends the image, as a default signal does. */
        if (seen && sig_act[sig].handler == SIG_DFL)
            sig_terminate(sig);
        return;
    }
    if (h == SIG_DFL) {
        sig_terminate(sig);
        return;
    }
    sig_run(sig, 0);
}

/* Deliver every pending signal the mask now lets through, lowest first. */
static void sig_flush(void)
{
    for (;;) {
        uint64_t ready = sig_pending & ~sig_mask;
        if (!ready || ovmx_crtl_sig_busy)
            return;
        int sig = 1;
        while (!(ready & BIT(sig)))
            sig++;
        sig_pending &= ~BIT(sig);
        sig_deliver(sig);
    }
}

/* A signal for this process: delivered now, or held while blocked/busy. */
static void sig_post(int sig)
{
    if (sig < 1 || sig > SIG_MAX)
        return;
    if (sig_act[sig].handler == SIG_IGN && !(BIT(sig) & UNBLOCKABLE))
        return;                        /* discarded, never pending */
    sig_pending |= BIT(sig);
    sig_flush();
}

void ovmx_crtl_sig_flush(void)
{
    if (sig_pending)
        sig_flush();
}

/* ---------------------------------------------------- process identity -- */

/* This process's VMS PID (not cached: a fork child is another process). */
static unsigned int my_pid(void)
{
    unsigned int pid = 0;
    uint16_t rl = 0;
    uint16_t iosb[4] = { 0 };
    struct sig_ile3 il[2];
    memset(il, 0, sizeof il);
    il[0].buflen = 4;
    il[0].code = JPI_PID;
    il[0].buf = &pid;
    il[0].retlen = &rl;
    if (!(sys$getjpiw(EFN_C_ENF, 0, 0, il, iosb, 0, 0) & 1u))
        return 0;
    return pid;
}

static long long vms_errno(unsigned int st)
{
    if (st & 1u)
        return 0;
    if (st == SS_NONEXPR)
        return -ESRCH;
    if (st == SS_NOPRIV)
        return -EPERM;
    return -EINVAL;
}

/* kill(pid, sig) for a process other than this one: the process services on
 * its VMS PID, resolved and authorized by the executive. */
static long long kill_other(unsigned int pid, int sig)
{
    uint32_t c = sig_cond(sig);
    unsigned int p = pid, got = 0;

    switch (sig) {
    case 0: {
        uint16_t rl = 0, iosb[4] = { 0 };
        struct sig_ile3 il[2];
        memset(il, 0, sizeof il);
        il[0].buflen = 4;
        il[0].code = JPI_PID;
        il[0].buf = &got;
        il[0].retlen = &rl;
        return vms_errno(sys$getjpiw(EFN_C_ENF, &p, 0, il, iosb, 0, 0));
    }
    case SIGKILL:
        return vms_errno(sys$delprc(&p, 0, 0));
    case SIGSTOP:
    case SIGTSTP:
        return vms_errno(sys$suspnd(&p, 0, 0));
    case SIGCONT:
        return vms_errno(sys$resume(&p, 0));
    default:
        /* the image is forced to exit with the signal's condition */
        return vms_errno(sys$forcex(&p, 0, ((c ? c : SS_ABORT) & ~7u) | SEV_SEVERE));
    }
}

/* ---------------------------------------------------------- timers ------ */

#define SIG_TIMER_REQIDT 0x0DEC5A1Au   /* this C RTL's ITIMER_REAL $SETIMR */

static uint64_t tmr_due;               /* VMS time it fires; 0 = disarmed */
static uint64_t tmr_interval;          /* 100 ns units; 0 = one-shot */
static unsigned tmr_gen;               /* bumped by every (re)arm/cancel */

static uint64_t vms_now(void)
{
    uint64_t t = 0;
    (void)sys$gettim(&t);
    return t;
}

static void tmr_ast(unsigned int reqidt);

static int tmr_arm(uint64_t delta)
{
    int64_t d = -(int64_t)(delta ? delta : 1);
    tmr_due = vms_now() + (delta ? delta : 1);
    return (sys$setimr(EFN_C_ENF, (const uint64_t *)&d, tmr_ast, SIG_TIMER_REQIDT, 0) & 1u) ? 0 : -1;
}

static void tmr_cancel(void)
{
    (void)sys$cantim(SIG_TIMER_REQIDT, PSL_C_USER);
    tmr_due = 0;
    tmr_gen++;
}

/* The $SETIMR AST: re-arm an interval timer, then SIGALRM. */
static void tmr_ast(unsigned int reqidt)
{
    if (reqidt != SIG_TIMER_REQIDT || !tmr_due)
        return;
    if (tmr_interval)
        (void)tmr_arm(tmr_interval);
    else
        tmr_due = 0;
    sig_post(SIGALRM);
    (void)sys$wake(0, 0);              /* end a pause() */
}

/* struct itimerval as musl passes it: {interval sec, usec, value sec, usec},
 * as long[4] where time_t is wider than long (the alpha-dec-vms port), else
 * the struct itself. */
static void itv_get(const void *p, uint64_t *interval, uint64_t *value)
{
    long long v[4];
    if (sizeof(time_t) > sizeof(long)) {
        const long *l = p;
        for (int i = 0; i < 4; i++) v[i] = l[i];
    } else {
        const struct itimerval *it = p;
        v[0] = it->it_interval.tv_sec; v[1] = it->it_interval.tv_usec;
        v[2] = it->it_value.tv_sec;    v[3] = it->it_value.tv_usec;
    }
    *interval = (uint64_t)v[0] * 10000000u + (uint64_t)v[1] * 10u;
    *value = (uint64_t)v[2] * 10000000u + (uint64_t)v[3] * 10u;
}

static void itv_put(void *p, uint64_t interval, uint64_t value)
{
    long long v[4] = { (long long)(interval / 10000000u), (long long)(interval % 10000000u / 10u),
                       (long long)(value / 10000000u),    (long long)(value % 10000000u / 10u) };
    if (sizeof(time_t) > sizeof(long)) {
        long *l = p;
        for (int i = 0; i < 4; i++) l[i] = (long)v[i];
    } else {
        struct itimerval *it = p;
        it->it_interval.tv_sec = v[0]; it->it_interval.tv_usec = v[1];
        it->it_value.tv_sec = v[2];    it->it_value.tv_usec = v[3];
    }
}

static uint64_t tmr_left(void)
{
    if (!tmr_due)
        return 0;
    uint64_t now = vms_now();
    return tmr_due > now ? tmr_due - now : 10;   /* due: 1 us left, not 0 */
}

static long long do_setitimer(long long which, const void *nv, void *ov)
{
    uint64_t iv, vv;
    if (which != ITIMER_REAL)
        return -EINVAL;
    if (ov)
        itv_put(ov, tmr_interval, tmr_left());
    if (!nv)
        return 0;
    itv_get(nv, &iv, &vv);
    tmr_cancel();
    tmr_interval = iv;
    if (!vv)
        return 0;
    return tmr_arm(vv) ? -EINVAL : 0;
}

/* ------------------------------------------------------ waiting ------- */

/* $HIBER until a signal's action has run. */
static long long sig_wait(void)
{
    unsigned seen = sig_delivered;
    sig_flush();
    while (sig_delivered == seen) {
        unsigned int st = sys$hiber();
        if (!(st & 1u))
            return -ENOSYS;            /* no executive: no wait to make */
    }
    return -EINTR;
}

/* ------------------------------------------------------- the hook ------ */

static uint64_t get_set(long long p)
{
    uint64_t s = 0;
    memcpy(&s, (const void *)(uintptr_t)p, sizeof s);
    return s;
}

static long long crtl_sig_serve(long long n, long long a1, long long a2,
                                long long a3, long long a4, int *handled)
{
    switch (n) {
    case SYS_rt_sigaction: {
        int sig = (int)a1;
        if (sig >= 32 && sig <= 64)
            return 0;                  /* the RTL's/LIBVMS's own (see top) */
        *handled = 1;
        if (sig < 1 || sig > SIG_MAX)
            return -EINVAL;
        if (a2 && (BIT(sig) & UNBLOCKABLE))
            return -EINVAL;            /* SIGKILL/SIGSTOP: cannot be caught */
        if (a3) {
            struct crtl_ksa *o = (struct crtl_ksa *)(uintptr_t)a3;
            memset(o, 0, sizeof *o);
            o->handler = sig_act[sig].handler;
            o->flags = sig_act[sig].flags;
            memcpy(o->mask, &sig_act[sig].mask, sizeof o->mask);
        }
        if (a2) {
            const struct crtl_ksa *k = (const struct crtl_ksa *)(uintptr_t)a2;
            uint64_t m = 0;
            memcpy(&m, k->mask, sizeof m);
            sig_act[sig].handler = k->handler;
#ifdef SA_RESTORER
            sig_act[sig].flags = k->flags & ~(unsigned long)SA_RESTORER;
#else
            sig_act[sig].flags = k->flags;
#endif
            sig_act[sig].mask = m & ~UNBLOCKABLE;
            if (k->handler == SIG_IGN ||
                (k->handler == SIG_DFL && sig_ignored_by_default(sig)))
                sig_pending &= ~BIT(sig);
        }
        return 0;
    }
    case SYS_rt_sigprocmask: {
        *handled = 1;
        uint64_t old = sig_mask;
        if (a2) {
            uint64_t s = get_set(a2) & ((1ull << SIG_MAX) - 1) & ~UNBLOCKABLE;
            if (a1 == SIG_BLOCK)        sig_mask |= s;
            else if (a1 == SIG_UNBLOCK) sig_mask &= ~s;
            else if (a1 == SIG_SETMASK) sig_mask = s;
            else return -EINVAL;
        }
        if (a3)
            memcpy((void *)(uintptr_t)a3, &old, sizeof old);
        sig_flush();
        return 0;
    }
    case SYS_rt_sigpending: {
        *handled = 1;
        uint64_t p = sig_pending;
        memcpy((void *)(uintptr_t)a1, &p, sizeof p);
        return 0;
    }
    case SYS_rt_sigsuspend: {
        *handled = 1;
        uint64_t old = sig_mask;
        sig_mask = get_set(a1) & ((1ull << SIG_MAX) - 1) & ~UNBLOCKABLE;
        long long r = sig_wait();
        sig_mask = old;
        sig_flush();
        return r;
    }
#ifdef SYS_pause
    case SYS_pause:
        *handled = 1;
        return sig_wait();
#endif
#ifdef SYS_ppoll
    case SYS_ppoll:                    /* musl's pause() where there is no SYS_pause */
        if (a1 || a2 || a3 || a4)
            return 0;
        *handled = 1;
        return sig_wait();
#endif
    case SYS_tkill:
        *handled = 1;
        sig_post((int)a2);
        return (a2 < 0 || a2 > 64) ? -EINVAL : 0;
#ifdef SYS_tgkill
    case SYS_tgkill:
        *handled = 1;
        sig_post((int)a3);
        return (a3 < 0 || a3 > 64) ? -EINVAL : 0;
#endif
    case SYS_kill: {
        *handled = 1;
        int sig = (int)a2;
        if (sig < 0 || sig > SIG_MAX)
            return -EINVAL;
        if (a1 < 0)
            return -EINVAL;            /* no process groups on VMS */
        if (a1 == 0 || (unsigned int)a1 == my_pid()) {
            if (sig)
                sig_post(sig);
            return 0;
        }
        return kill_other((unsigned int)a1, sig);
    }
    case SYS_setitimer:
        *handled = 1;
        return do_setitimer(a1, (const void *)(uintptr_t)a2, (void *)(uintptr_t)a3);
    case SYS_getitimer:
        *handled = 1;
        if (a1 != ITIMER_REAL)
            return -EINVAL;
        itv_put((void *)(uintptr_t)a2, tmr_interval, tmr_left());
        return 0;
#ifdef SYS_alarm
    case SYS_alarm: {
        *handled = 1;
        uint64_t left = tmr_left();
        tmr_cancel();
        tmr_interval = 0;
        if (a1)
            (void)tmr_arm((uint64_t)a1 * 10000000u);
        return (long long)((left + 9999999u) / 10000000u);
    }
#endif
#ifdef SYS_sigaltstack
    case SYS_sigaltstack:
#endif
    case SYS_rt_sigtimedwait:
    case SYS_rt_sigqueueinfo:
        *handled = 1;
        return -ENOSYS;
    default:
        return 0;
    }
}

/* Called first by the C RTL file layer's system-call hook. */
long long ovmx_crtl_signal_hook(long long n, long long a1, long long a2,
                                long long a3, long long a4, int *handled)
{
    if (!sig_on)
        return 0;
    return crtl_sig_serve(n, a1, a2, a3, a4, handled);
}

/* Turned on with the C RTL file layer (ovmx_crtl_fd_install, from decc$main):
 * the C RTL's condition handler goes on the secondary exception vector. */
void ovmx_crtl_signal_install(void)
{
    void *prev = 0;
    if (sig_on)
        return;
    for (int s = 1; s <= SIG_MAX; s++)
        sig_act[s].handler = SIG_DFL;
    (void)sys$setexv(CHF_SECONDARY_VECTOR, (void *)sig_condition, PSL_C_USER, &prev);
    sig_on = 1;
}
