/*
 * prv_names.h - Single X-macro source for vms_priv_names[] (the DCL
 *               privilege display table, src/vmsdcl/dcl_cmd_show.c) and
 *               for the compile-time coverage mask checked against
 *               VMS_PRV_M_ENFORCED in src/libvms/prv_agreement.c (vms-2b8
 *               round 10).
 *
 * WHY THIS FILE EXISTS. Round 9's prv_agreement.c added a _Static_assert
 * that VMS_PRV_M_ENFORCED (src/kernel/vms_ioctl.h) names no bit outside a
 * HAND-TYPED list `(PRV$M_CMKRNL | PRV$M_CMEXEC | PRV$M_SETPRV |
 * PRV$M_WORLD)`. That list was maintained by a human reading
 * vms_priv_names[] and copying which of its rows cover VMS_PRV_M_ENFORCED
 * -- it asserted the whitelist agreed with ITSELF, not with the array. An
 * adversary proved the gap by deleting the WORLD row from vms_priv_names[]
 * outright: the build still succeeded, because nothing in prv_agreement.c
 * ever looked at the array's actual contents, only at a second, independent
 * copy of "which four" a person had typed by hand.
 *
 * THE FIX moves that array's actual content into ONE preprocessor list
 * (VMS_PRIV_NAME_LIST below) and derives BOTH consumers from it:
 *   - dcl_cmd_show.c's vms_priv_names[] is generated by expanding this
 *     list through VMS_PRIV_ROW_ENTRY, one struct initializer per line.
 *   - prv_agreement.c's coverage mask (VMS_PRIV_NAMES_TABLE_MASK) is the
 *     OR of every mask in this SAME list, expanded through
 *     VMS_PRIV_MASK_TERM.
 * Deleting a line from VMS_PRIV_NAME_LIST removes that privilege from the
 * displayed table AND from the coverage mask in the same edit, because
 * both are generated from that one line. Measured: deleting the WORLD
 * line fails the build at prv_agreement.c's assert, and so does OR-ing an
 * uncovered bit into VMS_PRV_M_ENFORCED -- the desync is a compile error
 * in both directions. See prv_agreement.c for the assert and its two
 * negative controls.
 *
 * WHAT THIS DOES NOT COVER, measured rather than assumed: the guarantee
 * holds while vms_priv_names[] is GENERATED from this list. Replacing the
 * VMS_PRIV_NAME_LIST(VMS_PRIV_ROW_ENTRY) expansion in dcl_cmd_show.c with
 * hand-typed rows that omit one privilege builds clean and passes ctest --
 * the coverage mask still names the bit, the array no longer carries the
 * row, and nothing stops it. Keep the array generated.
 *
 * CONTENT is unchanged from the array round 9 shipped: same 37 entries,
 * same order, same names, same masks, same description strings. DETACH
 * and SETPRI (and every other prvdef.h bit vms_priv_names[] never carried)
 * are still deliberately absent -- CLAUDE.md Rule 10, unchanged by this
 * refactor.
 */

