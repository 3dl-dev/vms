/*
 * crtl_signal.c - the C RTL's signals are VMS conditions, ASTs and process
 * services (vms-931).
 *
 * HOW OPENVMS DOES IT (HP C Run-Time Library Reference Manual for OpenVMS
 * Systems, ch. 4 "Error and Signal Handling", Table 4-5 "HP C RTL Signals and
 * Corresponding OpenVMS Alpha Exceptions"). A C signal on OpenVMS is not a
 * kernel facility. The C RTL keeps each signal's action and the signal mask
 * itself, and connects them to VMS events:
 *
 *   - raise()/gsignal() translate the signal number to its OpenVMS exception
 *     and pass it to LIB$SIGNAL. The C RTL catches the exceptions in a VMS
 *     condition handler outside every frame handler of the program (the one it
 *     establishes in main), maps the condition back to the signal and calls the
 *     program's action. So an ACCVIO a program takes -- or any LIB$SIGNAL of
 *     SS$_ACCVIO -- reaches a SIGBUS/SIGSEGV handler, and a VAXC$ESTABLISH'd
 *     handler sees the condition first.
 *   - alarm()/setitimer(ITIMER_REAL) are a timer AST: SIGALRM's exception is
 *     SS$_ASTFLT ("generated by the alarm function").
 *   - kill() to another process is a process service; SIGKILL's exception is
 *     SS$_ABORT ("external signal only").
 *   - By default a signal (except SIGCHLD) terminates the image.
 *
 * HOW OVMX DOES IT. DECC$SHR is musl; every musl signal entry point (signal,
 * sigaction, sigprocmask, raise, kill, abort, alarm, setitimer, getitimer,
 * pause, sigsuspend, sigpending) ends in a system call through the C RTL's
 * funnel (__vms_alpha_syscall / x86_64 __ovmx_syscall). ovmx_crtl_signal_hook,
 * called first by the C RTL file layer's hook (crtl_rms_fd.c rms_hook), serves
 * all of them here, over VMS services only:
 *
 *   rt_sigaction        the C RTL's own action table (sig_act below)
 *   rt_sigprocmask,     the C RTL's own mask and pending set; a signal that
 *   rt_sigpending       arrives blocked is held and delivered on unblock
 *   tkill/tgkill, kill  raise: LIB$SIGNAL of the signal's condition (table
 *     (self)            sig_cond); a signal with no SS$ condition is delivered
 *                       by the C RTL directly (see C$_ below)
 *   kill (another VMS   $FORCEX (SIGKILL: $DELPRC, SIGSTOP: $SUSPND,
 *     process)          SIGCONT: $RESUME, 0: $GETJPIW), on the VMS PID, through
 *                       the executive; SS$_NONEXPR -> ESRCH, SS$_NOPRIV -> EPERM
 *   setitimer, alarm,   $SETIMR with an AST (reqidt SIG_TIMER_REQIDT) and
 *     getitimer         $CANTIM; the AST signals SS$_ASTFLT -> SIGALRM
 *   pause, sigsuspend   $HIBER until a signal's action has run (each delivery
 *     (ppoll 0,0,0,0)   $WAKEs the process)
 *
 * The condition handler is the SECONDARY exception vector ($SETEXV): the CHF
 * searches it after every frame handler (lib_signal.c dispatch_condition) --
 * the place the handler DEC C establishes in main holds on OpenVMS -- and it
 * returns SS$_RESIGNAL for every condition it does not turn into a caught
 * signal, so an action-less condition takes the normal VMS default (the
 * last-chance vector, then the message and image exit for a severe one).
 *
 * NOT HERE, AND WHY (rd children of vms-931: vms-1dd, vms-a78f, vms-92a6):
 *   - C$_SIGUSR1/C$_SIGUSR2/C$_SIGCHLD/C$_SIGWINCH/C$_SIGPIPE: the DEC C
 *     facility's condition values are not in the pinned SSDEF/message oracle
 *     (docs/oracle/alpha84-starlet-defs/SSDEF.txt), so those signals, and the
 *     ones Table 4-5 gives no exception, are delivered by the C RTL directly
 *     rather than through LIB$SIGNAL with an invented value. SIGPIPE uses
 *     SS$_NOMBX, which is pinned.
 *   - kill() of ANOTHER process runs no handler in it: the executive has no
 *     $SIGPRC-equivalent that delivers a condition into a process, so the
 *     target's image is forced to exit ($FORCEX) as the pre-V7.0 C RTL did.
 *   - Signals the substrate kernel raises on its own (a terminal's Ctrl/C, a
 *     fault without LIBVMS's fault bridge) keep the substrate's disposition;
 *     Ctrl/C as SIGINT is a Ctrl/C AST on the terminal channel.
 *   - Realtime signals (>= 32) are the RTL's and LIBVMS's own (musl's thread
 *     internals; the x86_64 LIBVMS $SETIMR queue's SIGRTMIN): no DEC C signal
 *     is numbered there (Table 4-5 ends at SIGUSR2 = 31), so they stay the
 *     substrate's.
 *   - ITIMER_VIRTUAL/ITIMER_PROF, sigaltstack, sigtimedwait/sigwaitinfo:
 *     EINVAL/ENOSYS, honestly, not a timer or wait that shares no real state.
 *
 * One thread: the action table, mask and pending set are the process's, as
 * the C RTL's are; an AST that lands while the file layer is inside RMS is
 * held (ovmx_crtl_sig_busy) and delivered when it leaves.
 */
